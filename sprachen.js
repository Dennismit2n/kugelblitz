  // --- Funktionen -----------------------------------------------------------------------------------

  function sprache(code) {
    return SPRACHEN.find((s) => s.code === code) || SPRACHEN[0];
  }

  // Wie Hourbridge: gespeicherte Wahl, sonst die erste unterstützte aus navigator.languages (nur der Sprachteil,
  // „fr-CA“ wird „fr“), sonst Englisch
  function erkenne(gespeichert, liste) {
    if (gespeichert && CODES.has(gespeichert)) return gespeichert;
    const kandidaten = (liste || []).map((x) => String(x).toLowerCase().split("-")[0]);
    return kandidaten.find((x) => CODES.has(x)) || "en";
  }

  const formate = new Map();
  function format(code, art, optionen) {
    const schl = code + "|" + art;
    let f = formate.get(schl);
    if (!f) {
      f = new Intl.NumberFormat(sprache(code).locale, optionen);
      formate.set(schl, f);
    }
    return f;
  }
  // Ganze Zahl mit Tausendertrennung je Sprache (de 1.234.567, en 1,234,567, fr 1 234 567, hi 12,34,567)
  function zahl(code, n) { return format(code, "zahl", { maximumFractionDigits: 0 }).format(Math.round(Number(n) || 0)); }
  // Zahl mit festen Nachkommastellen (Physik-Kachel)
  function dezimal(code, n, stellen) { return format(code, "d" + stellen, { minimumFractionDigits: stellen, maximumFractionDigits: stellen }).format(Number(n) || 0); }
  // Prozent (de „70 %“, en „70%“, tr „%70“)
  function prozent(code, n) { return format(code, "prozent", { style: "percent", maximumFractionDigits: 0 }).format((Number(n) || 0) / 100); }

  // Datum der Bestenliste aus „JJJJ-MM-TT“, in UTC gerechnet, damit kein Tag verrutscht
  const datumsformate = new Map();
  function datum(code, iso) {
    const t = typeof iso === "string" ? iso.split("-").map(Number) : [];
    if (t.length !== 3 || t.some((x) => !Number.isFinite(x))) return "";
    let f = datumsformate.get(code);
    if (!f) {
      f = new Intl.DateTimeFormat(sprache(code).locale, { day: "2-digit", month: "2-digit", year: "numeric", timeZone: "UTC" });
      datumsformate.set(code, f);
    }
    return f.format(Date.UTC(t[0], t[1] - 1, t[2]));
  }

  // Text zu einem Schlüssel, Platzhalter gefüllt (Zahlen je Sprache formatiert). Fehlt ein Text, steht Englisch da,
  // fehlt auch der, der Schlüssel selbst (fällt beim Prüfen auf).
  function text(code, schluessel, werte) {
    let t = (TEXTE[code] || {})[schluessel];
    if (t === undefined) t = TEXTE.en[schluessel];
    if (t === undefined) return schluessel;
    if (!werte) return t;
    return t.replace(/\{(\w+)\}/g, (ganz, name) => {
      const v = werte[name];
      if (v === undefined || v === null) return ganz;
      return typeof v === "number" ? zahl(code, v) : String(v);
    });
  }

  return { SPRACHEN, TEXTE, MISSIONSZIELE, SCHLUESSEL_SPEICHER, sprache, erkenne, zahl, dezimal, prozent, datum, text };
